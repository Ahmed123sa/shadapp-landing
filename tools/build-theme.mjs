#!/usr/bin/env node
// Builds site/assets/css/tokens.css from tokens/design-tokens.json with the
// ux-ui-agent-skills token builder, then adds scoped [data-theme] blocks so a
// soft-white section can live inside the charcoal page.
//   node tools/build-theme.mjs [path-to-ux-ui-agent-skills]
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const kit = resolve(process.argv[2] || process.env.UX_KIT || 'G:/coding/Skills/ux-ui-agent-skills/ux-ui-agent-skills');
const css = execFileSync('node', [resolve(kit, 'scripts/build_tokens.mjs'), '--check', '--in', resolve(root, 'tokens/design-tokens.json')], { encoding: 'utf8' });

const rootBlock = css.match(/:root \{([\s\S]*?)\n\}/)[1];
const darkBlock = css.match(/:root\[data-theme="dark"\] \{([\s\S]*?)\n\}/)[1];
const colorLines = rootBlock.split('\n').filter((l) => /--color-|--shadow-focus-ring/.test(l)).join('\n');

const out = css
  .replace(':root[data-theme="dark"] {', ':root[data-theme="dark"],\n[data-theme="dark"] {')
  + `\n/* Light tier, scoped: a soft-white section inside the charcoal page. */\n[data-theme="light"] {${'\n' + colorLines}\n}\n`;
writeFileSync(resolve(root, 'site/assets/css/tokens.css'), out.replace(/^\/\*.*\*\//, '/* Generated by tools/build-theme.mjs from tokens/design-tokens.json. Do not edit by hand. */'));
console.log('tokens.css written');
